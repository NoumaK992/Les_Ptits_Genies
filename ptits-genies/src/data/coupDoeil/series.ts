/** Toutes les séries d'une difficulté donnée (1 à 4). */
export function seriesDeDifficulte(d: number): CoupDoeilSeries[] {
  return SERIES_LIST.filter((s) => s.difficulte === d)
}

/** Une série de la difficulté demandée, tirée au hasard (difficulté bornée entre 1 et 4). */
export function tirerSerie(d: number): CoupDoeilSeries {
  const niveau = Math.min(Math.max(Math.round(d), 1), 4)
  const candidates = seriesDeDifficulte(niveau)
  return candidates[Math.floor(Math.random() * candidates.length)]
}
